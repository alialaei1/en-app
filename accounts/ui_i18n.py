def tf(lang: str, key: str, **kwargs) -> str:
    text = t(lang, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


def t(lang: str, key: str) -> str:
    pack = UI_STRINGS.get(lang) or UI_STRINGS["en"]
    return pack.get(key) or UI_STRINGS["en"].get(key, key)


def ui_bundle(lang: str) -> dict:
    pack = UI_STRINGS.get(lang) or UI_STRINGS["en"]
    return dict(pack)


def localize_form_labels(form, lang: str, mapping: dict[str, str]) -> None:
    """mapping: field_name -> ui key"""
    for field_name, ui_key in mapping.items():
        if field_name in form.fields:
            form.fields[field_name].label = t(lang, ui_key)


def localize_form_help(form, lang: str, mapping: dict[str, str]) -> None:
    for field_name, ui_key in mapping.items():
        if field_name in form.fields:
            form.fields[field_name].help_text = t(lang, ui_key)


def request_app_lang(request) -> str:
    from .context_processors import APP_LANG_COOKIE
    from .models import Profile, ensure_profile

    if getattr(request, "user", None) is not None and request.user.is_authenticated:
        return ensure_profile(request.user).app_language or Profile.AppLanguage.EN
    lang = request.COOKIES.get(APP_LANG_COOKIE, Profile.AppLanguage.EN)
    if lang not in Profile.SUPPORTED_APP_LANGUAGES:
        return Profile.AppLanguage.EN
    return lang
